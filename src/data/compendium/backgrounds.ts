export function findBackgroundById(id: string): CompendiumBackground | undefined {
  return DND_COMPENDIUM_BACKGROUNDS.find(b => b.id.toLowerCase() === id.toLowerCase());
}

export function findBackgroundByName(name: string): CompendiumBackground | undefined {
  const q = name.toLowerCase().trim();
  return DND_COMPENDIUM_BACKGROUNDS.find(b =>
    b.name.toLowerCase() === q ||
    b.nameEn.toLowerCase() === q ||
    b.id.toLowerCase() === q
  );
}
