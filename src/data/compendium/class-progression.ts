const CLASS_NAME_MAP: Record<string, string> = {
  'варвар': 'Варвар', 'barbarian': 'Варвар',
  'воин': 'Воин', 'fighter': 'Воин',
  'плут': 'Плут', 'rogue': 'Плут',
  'паладин': 'Паладин', 'paladin': 'Паладин',
  'волшебник': 'Волшебник', 'wizard': 'Волшебник',
  'жрец': 'Жрец', 'cleric': 'Жрец',
  'друид': 'Друид', 'druid': 'Друид',
  'бард': 'Бард', 'bard': 'Бард',
  'монах': 'Монах', 'monk': 'Монах',
  'следопыт': 'Следопыт', 'ranger': 'Следопыт',
  'чародей': 'Чародей', 'sorcerer': 'Чародей',
  'колдун': 'Колдун', 'warlock': 'Колдун',
  'изобретатель': 'Изобретатель', 'artificer': 'Изобретатель'
};

export function normalizeClassName(name: string): string {
  if (!name) return 'Воин';
  const clean = name.trim().toLowerCase();
  for (const [k, v] of Object.entries(CLASS_NAME_MAP)) {
    if (clean.includes(k)) return v;
  }
  return 'Воин';
}

export function isClassASILevel(className: string, level: number): boolean {
  const norm = normalizeClassName(className);
  const prog = DND_CLASS_PROGRESSION[norm];
  if (prog && prog.asiLevels) {
    return prog.asiLevels.includes(level);
  }
  return [4, 8, 12, 16, 19].includes(level);
}

export function getClassSubclassLevel(className: string): number {
  const norm = normalizeClassName(className);
  const prog = DND_CLASS_PROGRESSION[norm];
  return prog?.subclassLevel ?? 3;
}

export function isClassSubclassMilestone(className: string, level: number): boolean {
  const norm = normalizeClassName(className);
  const prog = DND_CLASS_PROGRESSION[norm];
  return prog?.subclassFeatureLevels?.includes(level) ?? false;
}

export function getClassFeaturesForLevel(className: string, level: number): ClassFeatureEntry[] {
  const norm = normalizeClassName(className);
  const prog = DND_CLASS_PROGRESSION[norm];
  if (!prog) return [];
  return prog.featuresByLevel[String(level)] || [];
}

