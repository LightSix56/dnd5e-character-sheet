export function findClassById(id: string): CompendiumClass | undefined {
  return DND_COMPENDIUM_CLASSES.find(c => c.id === id);
}

export function findClassByName(name: string): CompendiumClass | undefined {
  if (!name) return undefined;
  const q = name.trim().toLowerCase();
  return DND_COMPENDIUM_CLASSES.find(c => 
    c.name.toLowerCase() === q || 
    c.nameEn.toLowerCase() === q
  );
}

export function getSubclassesForClass(classIdOrName: string): CompendiumSubclass[] {
  const cls = findClassById(classIdOrName) || findClassByName(classIdOrName);
  return cls ? cls.subclasses : [];
}
