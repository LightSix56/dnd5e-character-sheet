/**
 * Normalizes user/compendium race input to a known database key.
 */
export function normalizeRaceKey(race: string): string {
  const r = (race || '').toLowerCase().trim();
  for (const [key, entry] of Object.entries(DND_COMPENDIUM_NAMES_DB)) {
    if (key === r || entry.aliases.some(a => r.includes(a) || a.includes(r))) {
      return key;
    }
  }
  return 'human';
}

/**
 * Returns available cultures / sub-traditions for the race.
 */
export function getAvailableCultures(raceKey: string): { id: string; name: string }[] {
  const entry = DND_COMPENDIUM_NAMES_DB[raceKey];
  if (!entry || !entry.cultures || entry.cultures.length === 0) {
    return [];
  }
  return entry.cultures.map(c => ({ id: c.id, name: c.name }));
}

/**
 * Random element picker helper.
 */
function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Generates an authentic fantasy name with etymology and lore from dnd.su.
 */
export function generateFantasyName(
  race: string,
  gender: 'male' | 'female' | 'any' = 'any',
  specificCulture?: string
): FantasyNameResult {
  const key = normalizeRaceKey(race);
  const entry = DND_COMPENDIUM_NAMES_DB[key] || DND_COMPENDIUM_NAMES_DB['human'];

  let firstName = '';
  let surname = '';
  let cultureLabel = entry.name;
  let meaning = entry.namingTradition;

  // Check if race has subcultures (like Humans or Genasi)
  if (entry.cultures && entry.cultures.length > 0) {
    let chosenCulture = entry.cultures[0];
    if (specificCulture && specificCulture !== 'all') {
      const found = entry.cultures.find(c => c.id === specificCulture);
      if (found) chosenCulture = found;
    } else {
      chosenCulture = pickRandom(entry.cultures);
    }
    cultureLabel = `${entry.name} (${chosenCulture.name})`;

    const useMale = gender === 'male' || (gender === 'any' && Math.random() > 0.5);
    const pool = useMale ? chosenCulture.maleNames : chosenCulture.femaleNames;
    firstName = pickRandom(pool.length > 0 ? pool : chosenCulture.maleNames);

    if (chosenCulture.surnames && chosenCulture.surnames.length > 0) {
      surname = pickRandom(chosenCulture.surnames);
    }
    meaning = `Культурная традиция: ${chosenCulture.name}. Личное имя: ${firstName}${surname ? `, фамилия: ${surname}` : ''}.`;
  } else {
    // Standard race without subcultures
    const hasMale = entry.maleNames && entry.maleNames.length > 0;
    const hasFemale = entry.femaleNames && entry.femaleNames.length > 0;
    const hasUnisex = entry.unisexNames && entry.unisexNames.length > 0;

    let pool: string[] = [];
    if (gender === 'male' && hasMale) {
      pool = entry.maleNames!;
    } else if (gender === 'female' && hasFemale) {
      pool = entry.femaleNames!;
    } else if (gender === 'any' && (hasMale || hasFemale)) {
      pool = [...(entry.maleNames || []), ...(entry.femaleNames || [])];
    } else if (hasUnisex) {
      pool = entry.unisexNames!;
    } else {
      pool = entry.maleNames || entry.femaleNames || ['Герой'];
    }

    // Special check for tiefling virtues
    if (key === 'tiefling' && entry.virtueNames && Math.random() < 0.3) {
      firstName = pickRandom(entry.virtueNames);
      meaning = `Имя-добродетель: «${firstName}» — цель и жизненный обет тифлинга.`;
    } else {
      firstName = pickRandom(pool);
      if (entry.surnames && entry.surnames.length > 0 && Math.random() > 0.15) {
        surname = pickRandom(entry.surnames);
      }
      meaning = `Официальная традиция ${entry.name} (dnd.su). ${entry.namingTradition}`;
    }
  }

  const fullName = surname ? `${firstName} ${surname}` : firstName;

  return {
    name: fullName,
    meaning,
    culture: cultureLabel,
  };
}

/**
 * Generates multiple unique names at once.
 */
export function generateMultipleFantasyNames(
  race: string,
  gender: 'male' | 'female' | 'any' = 'any',
  count: number = 4,
  specificCulture?: string
): FantasyNameResult[] {
  const results: FantasyNameResult[] = [];
  const seen = new Set<string>();

  for (let i = 0; i < count * 3 && results.length < count; i++) {
    const res = generateFantasyName(race, gender, specificCulture);
    if (!seen.has(res.name)) {
      seen.add(res.name);
      results.push(res);
    }
  }

  while (results.length < count) {
    results.push(generateFantasyName(race, gender, specificCulture));
  }

  return results;
}

