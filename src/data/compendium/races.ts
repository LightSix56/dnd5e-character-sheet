export function findRaceById(id: string): CompendiumRace | undefined {
  return DND_COMPENDIUM_RACES.find(r => r.id === id);
}

export function findRaceByName(name: string): CompendiumRace | undefined {
  if (!name) return undefined;
  const q = name.trim().toLowerCase();
  return DND_COMPENDIUM_RACES.find(r => 
    r.name.toLowerCase() === q || 
    r.nameEn.toLowerCase() === q
  );
}
