export function findSpellByName(name: string): DndSpell | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return DND_SPELLS.find(s => s.name.toLowerCase() === clean || clean.startsWith(s.name.toLowerCase()) || s.name.toLowerCase().startsWith(clean));
}
