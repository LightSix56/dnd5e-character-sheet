export function findTraitByName(name: string): DndTrait | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return DND_TRAITS.find(t => t.name.toLowerCase() === clean || clean.startsWith(t.name.toLowerCase()) || t.name.toLowerCase().startsWith(clean));
}
