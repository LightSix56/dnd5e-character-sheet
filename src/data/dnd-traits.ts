export const DND_TRAITS: DndTrait[] = [
  ...ALTERNATE_BARBARIAN_TRAITS,
  ...BARBARIAN_EXPLOIT_TRAITS,
  ...DND_COMPENDIUM_FEATS.map(f => ({
    name: f.name,
    source: f.source || (f.category === 'Черта' ? 'Черта (Feat)' : 'Способность'),
    category: f.category,
    summary: f.summary,
    description: f.description
  }))
];

export function findTraitByName(name: string): DndTrait | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();

  // 1. Exact match (case-insensitive) - MUST always take precedence over partial/prefix matches!
  const exact = DND_TRAITS.find(t => t.name.toLowerCase() === clean);
  if (exact) return exact;

  // 2. If name starts with "Боевой приём: ...", strip prefix and check exact match
  if (clean.startsWith('боевой приём:')) {
    const stripped = clean.replace(/^боевой приём:\s*/, '');
    const foundStripped = DND_TRAITS.find(t => t.name.toLowerCase() === stripped);
    if (foundStripped) return foundStripped;
  }

  // 3. User input starts with trait name (e.g. "Ярость (2/отдых)" -> "Ярость")
  const prefixTrait = DND_TRAITS.find(t => clean.startsWith(t.name.toLowerCase()));
  if (prefixTrait) return prefixTrait;

  // 4. Trait name starts with user input (fallback for autocomplete typing, e.g. "Неистов" -> "Неистовство")
  const startsWithClean = DND_TRAITS.find(t => t.name.toLowerCase().startsWith(clean));
  if (startsWithClean) return startsWithClean;

  return undefined;
}
